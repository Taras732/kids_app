// Контент-банк «активностей дня» (BRIEF SHK-C3).
// Активність — офлайн-крок плану дня поза екраном: орігамі, простий рецепт
// без плити/ножа, творчий проєкт. Дитина робить руками, дорослий (за потреби)
// лише допомагає; результат позначається «зроблено» в застосунку.
//
// Формат payload узгоджено зі схемою навчального ядра: кожна активність
// конвертується в `OfflineTask` (type='activity') через `toOfflineTaskSeed`.
// Ілюстрації — пізніше (пайплайн F2); поки картка текстова + emoji.
import type { GradeBand, OfflineTask } from '../school/types';

/** Підтип активності (для іконки/фільтра в картці). */
export type ActivityCategory = 'origami' | 'recipe' | 'craft';

/**
 * Скільки потрібно дорослого:
 *  - 'none'     — дитина робить сама (оркестратор може дати без батьків);
 *  - 'light'    — дорослий поруч показує/підстраховує;
 *  - 'required' — дорослий робить небезпечну частину (наприклад, ріже).
 */
export type AdultHelp = 'none' | 'light' | 'required';

/** Тіло `OfflineTask.payload` для активності. */
export interface ActivityPayload {
  category: ActivityCategory;
  /** Emoji-іконка картки (fallback до ілюстрацій F2). */
  icon: string;
  /** Один рядок «що це» — показуємо під назвою. */
  summary: string;
  ageMin: number;
  ageMax: number;
  estimatedMinutes: number;
  adultHelp: AdultHelp;
  /** Що приготувати (матеріали/інгредієнти). */
  materials: string[];
  /** Покрокова інструкція дитячою мовою. */
  steps: string[];
  /** Необов'язкова підказка «як зробити краще/цікавіше». */
  tip?: string;
  /** Необов'язкове застереження безпеки (показуємо помітно). */
  safetyNote?: string;
}

/** Готова активність банку (лягає в довідник `offline_tasks`). */
export interface Activity {
  id: string;
  title: string;
  grade_band: GradeBand;
  payload: ActivityPayload;
}

