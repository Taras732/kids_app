/** Повний банк активностей (20). */
export const ACTIVITIES: Activity[] = [...ORIGAMI, ...RECIPES, ...CRAFTS];

/** Активність за id (undefined, якщо немає). */
export function getActivity(id: string): Activity | undefined {
  return ACTIVITIES.find((a) => a.id === id);
}

/**
 * Активності для рівня дитини — для планувальника «Мій день» (B1).
 * Повертає активності рівно цього grade_band; за потреби планувальник
 * може розширити пошук на сусідні рівні.
 */
export function getActivitiesForBand(band: GradeBand): Activity[] {
  return ACTIVITIES.filter((a) => a.grade_band === band);
}

/** Активності підтипу (origami/recipe/craft). */
export function getActivitiesByCategory(category: ActivityCategory): Activity[] {
  return ACTIVITIES.filter((a) => a.payload.category === category);
}

/**
 * Конвертувати активність у seed-рядок довідника `offline_tasks`
 * (id/created_at проставляє БД). Міст до офлайн-флоу C1.
 */
export function toOfflineTaskSeed(a: Activity): Omit<OfflineTask, 'created_at'> {
  return {
    id: a.id,
    type: 'activity',
    title: a.title,
    payload: a.payload as unknown as Record<string, unknown>,
    grade_band: a.grade_band,
  };
}
